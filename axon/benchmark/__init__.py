"""Benchmark integration for AXON (SEGMENT 11, real adapters).

Four external CTF/pentest benchmarks are wired in behind the common harness interface:

* ``nyuctf``       — NYU CTF Bench (200 tasks) — SOTA comparison; HIGH contamination risk.
* ``autopenbench`` — AutoPenBench — milestone/partial-credit scoring; vs. Pentest-R1.
* ``cybench``      — Cybench — SOTA comparison, subtask scoring; HIGH contamination risk.
* ``xbow``         — XBOW / XBEN (104 web challenges) — low-contamination (injected random
                     flags); the cleanest signal.

The benchmarks themselves are multi-gigabyte (Docker challenge environments, binaries). They are
NOT vendored into this repo. Instead:

* each benchmark's **task index** (metadata only — ids, categories, difficulty; *no flags, no
  solution prompts*, to avoid committing contamination) lives in ``indices/<name>.json`` and is
  regenerated by :mod:`axon.benchmark.build_indices`;
* the heavy challenge data is located at runtime by :mod:`axon.benchmark.paths` via an env var
  (``AXON_BENCH_ROOT`` / ``AXON_BENCH_<NAME>``) or a sensible default path.

``load_tasks()`` works from the committed indices (real task lists). ``start()`` needs the full
data plus a container runtime and is a labeled stub until that is wired per deployment.
"""

